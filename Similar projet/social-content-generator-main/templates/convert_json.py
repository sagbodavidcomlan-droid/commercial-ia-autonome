import json
import csv

# Baca JSON template
with open('google_sheet_template.json', 'r') as f:
    data = json.load(f)

# Extract headers
headers = [col['name'] for col in data['columns']]
headers.extend([col['name'] for col in data['autoGeneratedColumns']])

# Write CSV
with open('google_sheet_template.csv', 'w', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(headers)
    
    # Write sample data
    for sample in data['sampleData']:
        row = []
        for header in headers:
            row.append(sample.get(header, ''))
        writer.writerow(row)

print("CSV file created: google_sheet_template.csv")